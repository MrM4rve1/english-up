#!/usr/bin/env python3
"""Generate validated A2–B2 instructional content. No runtime dependency on Python."""
import json,re,runpy,pathlib
root=pathlib.Path(__file__).resolve().parent.parent
records=[]
def add(level,id,title,desc,formula,usage,structure,contrast,examples,pitfalls,markers=''):
    rows=[]
    for line in examples.strip().splitlines():
        if not line.strip(): continue
        pieces=[x.strip() for x in line.split('|')]
        assert len(pieces) in (2,3),(id,line)
        en,ru=pieces[:2]
        match=re.findall(r'\[([^\[\]]+)\]',en)
        assert len(match)==1,(id,en)
        opts=[x.strip() for x in match[0].split('~')]
        assert len(opts)==3 and len(set(opts))==3,(id,en,opts)
        correct=opts[0]
        sentence=re.sub(r'\[([^\[\]]+)\]',lambda _:correct,en)
        assert sentence.endswith(('.', '?', '!')),(id,sentence)
        rows.append(dict(en=sentence,ru=ru,cloze=en.replace('['+match[0]+']','___'),answer=correct,options=opts,explain=pieces[2] if len(pieces)==3 else ''))
    errors=[]
    for line in pitfalls.strip().splitlines():
        if not line.strip():continue
        pieces=[s.strip() for s in line.split('|')]
        assert len(pieces)==3,(id, line)
        errors.append(dict(wrong=pieces[0],right=pieces[1],why=pieces[2]))
    assert level in ('A2','B1','B2')
    assert len(rows)==13,(id,len(rows))
    assert len(set(x['en'] for x in rows))==13,(id,'duplicate sentence')
    assert len(errors)==2,(id,errors)
    assert all(len(s)>60 for s in [usage,structure,contrast]),(id,'short explanation')
    assert id not in [x['id'] for x in records],id
    records.append(dict(id=id,level=level,title=title,desc=desc,formula=formula,usage=usage,structure=structure,contrast=contrast,rows=rows,pitfalls=errors,markers=[m.strip() for m in markers.split(';') if m.strip()]))
for level in ['a2','b1','b2']:
    source=root/'tools'/f'level_{level}.py'
    exec(compile(source.read_text(),str(source),'exec'),{'add':add})
assert len(records)>=50,len(records)
legacy={'present-perfect','past-cont','conditional-1','extra-5','extra-6','extra-7','extra-8','passive','extra-9','extra-10','extra-11','extra-12','extra-13','extra-14','extra-15','extra-16'}
assert legacy.issubset({r['id'] for r in records})
# Exact typed content with validated 13 authentic example sentences per unit.
js=json.dumps(records,ensure_ascii=False,indent=2)
code='''// GENERATED by tools/build_levels.py (the lesson source files are in tools/).
// Structured authored A2–B2 material, no external API necessary.
import type {A1Unit,A1Exercise} from './a1-course.ts';
import type {Lesson} from './content.ts';
import {normalizedAnswer,checkA1Answer} from './a1-course.ts';
type SourceExample={en:string;ru:string;cloze:string;answer:string;options:string[];explain:string};
type SourceUnit={id:string;level:'A2'|'B1'|'B2';title:string;desc:string;formula:string;usage:string;structure:string;contrast:string;rows:SourceExample[];pitfalls:{wrong:string;right:string;why:string}[];markers:string[]};
const SOURCES:SourceUnit[] = '''+js+''';
export const UPPER_ORDER:readonly string[]=SOURCES.map(u=>u.id);
export const UPPER_BY_ID:Record<string,A1Unit>={};
export const UPPER_LEVELS:Record<string,'A2'|'B1'|'B2'>={};
function shuffle(text:string,seed:number):string[]{
 const out=text.trim().split(/\\s+/);
 for(let i=out.length-1;i>0;i--){const j=(i*11+seed*17+3)%(i+1);[out[i],out[j]]=[out[j],out[i]];}
 if(out.join(' ')===text.trim())out.reverse();return out;
}
export function makeAdvancedExercises(lesson:{id:string}):A1Exercise[]{
 const s=SOURCES.find(item=>item.id===lesson.id);if(!s)return [];
 const result:A1Exercise[]=[];
 s.rows.slice(0,7).forEach((r,i)=>{
  const correctIndex=(i*2+1)%3;
  const other=r.options.slice(1);
  const choices=[...other];choices.splice(correctIndex,0,r.answer);
  result.push({id:`${s.id}-choice-${i}`,type:'choice',prompt:r.cloze,why:r.explain||s.structure,choices,correctIndex,answers:[r.answer]});
 });
 s.rows.slice(7,13).forEach((r,i)=>result.push({id:`${s.id}-fill-${i}`,type:'fill',prompt:r.cloze,why:r.explain||s.structure,answers:[r.answer]}));
 // Sentence reconstruction checks exact word order, punctuation normalized by checker.
 const short=[...s.rows].map((r,i)=>({...r,i})).filter(r=>r.en.split(/\\s+/).length>=4).sort((a,b)=>a.en.split(/\\s+/).length-b.en.split(/\\s+/).length).slice(0,3);
 short.forEach((r,i)=>result.push({id:`${s.id}-order-${i}`,type:'order',prompt:'Собери предложение: '+r.ru,why:s.structure,words:shuffle(r.en,i),answers:[r.en]}));
 s.pitfalls.forEach((r,i)=>result.push({id:`${s.id}-fix-${i}`,type:'fix',prompt:'Исправь грамматическую ошибку:',source:r.wrong,why:r.why,answers:[r.right]}));
 s.rows.slice(11,13).forEach((r,i)=>result.push({id:`${s.id}-translate-${i}`,type:'translate',prompt:'Переведи на английский: '+r.ru,why:r.explain||s.usage,answers:[r.en]}));
 return result;
}
for(const s of SOURCES){
 UPPER_LEVELS[s.id]=s.level;
 UPPER_BY_ID[s.id]={id:s.id,title:s.title,desc:s.desc,formula:s.formula,
 sections:[{title:'Когда и зачем использовать',body:s.usage,model:s.rows[0].en},{title:'Как построить предложение',body:s.structure,model:s.rows[1].en},{title:'Нюансы, контекст и сравнения',body:s.contrast,model:s.rows[2].en},{title:'Ошибка, которую часто делают',body:`Неправильный вариант: «${s.pitfalls[0].wrong}». Правильный вариант: «${s.pitfalls[0].right}». ${s.pitfalls[0].why}`,model:s.pitfalls[0].right}],
 examples:s.rows.slice(0,10).map(r=>[r.en,r.ru] as [string,string]),
 blanks:s.rows.slice(7,13).map(r=>({prompt:r.cloze,answers:[r.answer],why:r.explain||s.structure})),
 orders:s.rows.slice(0,3).map(r=>({answer:r.en,prompt:r.ru,why:s.structure})),
 fixes:s.pitfalls.map(r=>({source:r.wrong,answers:[r.right],why:r.why})),
 translations:s.rows.slice(11,13).map(r=>({prompt:r.ru,answers:[r.en],why:r.explain||s.usage})),
 choices:s.rows.slice(0,7).map(r=>({q:r.cloze,choices:r.options,answer:0,why:r.explain||s.structure})),
 markers:s.markers.length?s.markers:['Контекст','Порядок слов'],pitfalls:s.pitfalls};
}
export function getUpperUnit(id:string):A1Unit|undefined{return UPPER_BY_ID[id];}
export function getUpperOrder(id:string):number{const n=UPPER_ORDER.indexOf(id);return n<0?999:n;}
export const UPPER_ADDITIONAL_LESSONS:Lesson[]=SOURCES.filter(s=>!'''+json.dumps(sorted(legacy))+'''.includes(s.id)).map(s=>({id:s.id,level:s.level,title:s.title,desc:s.desc,rule:s.usage,formula:s.formula,examples:s.rows.slice(0,10).map(r=>[r.en,r.ru]),questions:s.rows.slice(0,7).map(r=>({q:r.cloze,choices:r.options,answer:0,why:r.explain||s.structure}))}));
'''
(root/'lib'/'upper-course.ts').write_text(code)
print('generated',len(records),'lessons;',len(records)*13,'context sentences;',len(records)*20,'graded questions')
